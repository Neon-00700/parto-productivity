export function faStepsFor(name) {
  const key = String(name || '').toLowerCase().trim();
  return FA_STEPS[key] || null;
}

// Returns an array of Persian guidance sentences for any exercise.
export function faGuideFor(ex, lang = 'fa') {
  if (!ex) return [];
  const out = [];
  const eqTip = EQ_TIP[ex.eq] || 'این حرکت با وسیله انجام می‌شود.';
  const bpTip = BP_TIP[ex.bp] || 'روی بخش هدف تمرکز کن و حرکت را کنترل‌شده انجام بده.';
  const m = musclesOf(ex);
  const targets = Object.keys(m)
    .map((slug) => (MUSCLE_FA[slug] || slug))
    .join('، ');
  out.push(eqTip);
  out.push(bpTip);
  if (targets) out.push(`عضلات درگیر: ${targets}.`);
  out.push('قبل از شروع کمی گرم کن و در صورت درد، حرکت را متوقف کن.');
  return out;
}
