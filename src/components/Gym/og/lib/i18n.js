export function gymT(lang, key, ...args) {
  const table = dict[lang] || dict.en;
  let s = table[key];
  if (s === undefined) s = dict.en[key] !== undefined ? dict.en[key] : key;
  if (args && args.length) {
    args.forEach((a, i) => { s = s.replace(`{${i}}`, a); });
  }
  return s;
}

// Fall back to English for a key the chosen language lacks (e.g. exercise names).
export function tt(lang, key) {
  return dict[lang]?.[key] ?? dict.en[key] ?? key;
}
